// No dependencies; generate the browser bundle so index.html also works via file://.
import {readFile,writeFile} from 'node:fs/promises';
const base=new URL('../',import.meta.url);
const source=async file=>(await readFile(new URL('assets/'+file,base),'utf8')).replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
const core=await source('core.js'),api=await source('api.js'),app=await source('app.js');
const coreNames='esc,officeParts,addDays,minutes,timeString,times,overlap,validateBooking,mayEdit,roomArt';
const bundle=`// Generated by node scripts/build.mjs. Edit the source modules instead.\n(()=>{\n'use strict';\nconst Core=(()=>{\n${core}\nreturn {${coreNames}};})();\nconst API=(()=>{\nconst {${coreNames}}=Core;\n${api}\nreturn {api,live};})();\n(()=>{const {${coreNames}}=Core;const {api,live}=API;\n${app}\n})();\n})();\n`;
await writeFile(new URL('assets/app.bundle.js',base),bundle);
console.log(`Browser bundle: ${Buffer.byteLength(bundle)} bytes`);
